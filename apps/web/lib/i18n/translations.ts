export type TranslationKey = keyof typeof dict

function buildTable(locale: Locale): Record<TranslationKey, string> {
  const table = {} as Record<TranslationKey, string>
  for (const key of Object.keys(dict) as TranslationKey[]) {
    table[key] = dict[key][locale]
  }
  return table
}

export const translations: Record<Locale, Record<TranslationKey, string>> = {
  nb: buildTable('nb'),
  en: buildTable('en'),
}

export function normalizeLocale(value: string | null | undefined): Locale {
  return value === 'en' ? 'en' : 'nb'
}

// Supports simple {varName} interpolation for dynamic values (counts, names,
// dates). Pass vars as { n: 3 } etc — non-string values are stringified.
export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const template = translations[locale][key]
  if (!vars) return template
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template
  )
}

// For server components, which can't use the useLocale() hook (React
// context). Resolve the coach's locale from profiles.language server-side
// and call getTranslator(locale) once to get a plain t() function.
export function getTranslator(locale: Locale) {
  return (key: TranslationKey, vars?: Record<string, string | number>) => translate(locale, key, vars)
}
